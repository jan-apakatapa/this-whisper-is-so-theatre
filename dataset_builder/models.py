"""Структуры данных, используемые при формировании набора данных."""

from dataclasses import dataclass


@dataclass
class SegmentRecord:
    """Одна запись набора данных: аудиосегмент и его текстовая разметка.

    Атрибуты:
        id: Уникальный идентификатор сегмента (например, ``"0001"``).
        audio_path: Путь к WAV-файлу сегмента.
        text: Текстовая транскрипция (заполняется вручную при разметке).
        start_time: Время начала сегмента в исходной записи, с.
        end_time: Время окончания сегмента в исходной записи, с.
    """

    id: str
    audio_path: str
    text: str
    start_time: float
    end_time: float
